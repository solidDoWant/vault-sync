#!/usr/bin/env bash
# Compiles the Dafny modules in plugin/verified/ to one JavaScript file,
# plugin/src/verified/gen/verified.cjs, with the Dafny runtime included
# (make verified-js, a dependency of make plugin-build). `dafny translate js`
# emits a script that declares one top-level `let` per Dafny module; the
# CommonJS export appended here lets esbuild bundle it and the typed wrappers
# in plugin/src/verified/ import it. The output is committed (like gen/), so
# builds without Dafny (the native Windows/macOS e2e legs) still work, and
# make check-generate fails when it is stale.
set -euo pipefail
# Byte-order collation and untranslated messages, so the output is the same
# under every locale (the CI runner's C locale and a dev VM's en_US.UTF-8).
export LC_ALL=C

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

out_dir=plugin/src/verified/gen
out_file="$out_dir/verified.cjs"
work_dir="$(mktemp -d)"
trap 'rm -rf "$work_dir"' EXIT

shopt -s nullglob
sources=(plugin/verified/*.dfy)
if [ "${#sources[@]}" -eq 0 ]; then
  echo "verified-js: no Dafny sources in plugin/verified/" >&2
  exit 1
fi

# Translation verifies as well; make verify is the explicit, CI-gated check.
dafny translate js --include-runtime --no-verify \
  --translation-record-output "$work_dir/verified.dtr" \
  --output "$work_dir/verified" "${sources[@]}" >&2

# The exported names: the Dafny runtime and every top-level module.
modules="$(sed -n 's/^let \([A-Za-z_][A-Za-z0-9_]*\) = (function() {$/\1/p' "$work_dir/verified.js" | grep -v '^_module$' | sort -u | paste -sd, -)"
if [ -z "$modules" ]; then
  echo "verified-js: found no compiled modules in the Dafny output" >&2
  exit 1
fi

mkdir -p "$out_dir"
{
  echo "// Code generated by scripts/verified-js.sh from plugin/verified/*.dfy (Dafny $(dafny --version | head -n1)). DO NOT EDIT."
  cat "$work_dir/verified.js"
  echo
  echo "module.exports = { ${modules//,/, } };"
} > "$out_file"
echo "verified-js: wrote $out_file (modules: $modules)" >&2
