// The metrics reference page is generated here, in package server, because
// the full set of registered collectors is not observable through /metrics:
// a vector metric without observed label values is omitted from the
// exposition.

var updateMetricsReference = flag.Bool("update", false, "rewrite "+metricsReferencePath)

const metricsReferencePath = "../../docs/admin/metrics-reference.md"

type registeredMetric struct {
	name   string
	kind   string
	labels []string
	help   string
}

var descPattern = regexp.MustCompile(`^Desc\{fqName: "([^"]+)", help: ("(?:[^"\\]|\\.)*"), .*variableLabels: \{([^}]*)\}\}$`)

// perReplicaMetrics returns every vault_sync_* metric the server registers
// on the per-instance port, in registration order.
func perReplicaMetrics(t *testing.T) []registeredMetric {
	t.Helper()

	hub := realtime.NewHub(realtime.Options{})
	dependencies := DependencyMetrics{Database: store.NewMetrics(), ObjectStore: blobstore.NewMetrics(), OIDC: auth.NewMetrics()}

	return collectorMetrics(t, serverCollectors(hub, newRPCMetrics(), newConcurrencyMetrics(), retention.NewMetrics(), dependencies))
}

// collectorMetrics returns the name, type, label names and help of every
// metric of collected, in order.
func collectorMetrics(t *testing.T, collected []prometheus.Collector) []registeredMetric {
	t.Helper()

	registered := []registeredMetric{}

	for _, collector := range collected {
		var kind string

		// Gauge before Counter: a Gauge also satisfies the Counter interface.
		switch typed := collector.(type) {
		case prometheus.Gauge, *prometheus.GaugeVec:
			kind = "gauge"
		case prometheus.Counter, *prometheus.CounterVec:
			kind = "counter"
		case prometheus.Histogram, *prometheus.HistogramVec:
			kind = "histogram"
		case prometheus.Metric:
			// A GaugeFunc or CounterFunc: both have the same methods, so
			// its type is read from the metric it writes.
			kind = funcMetricKind(t, typed)
		default:
			require.Failf(t, "unknown collector type", "%T", collector)
		}

		descs := make(chan *prometheus.Desc, 16)
		collector.Describe(descs)
		close(descs)

		for desc := range descs {
			match := descPattern.FindStringSubmatch(desc.String())
			require.NotNil(t, match, "unparseable descriptor %s", desc)

			help, err := strconv.Unquote(match[2])
			require.NoError(t, err)

			labels := []string{}
			if match[3] != "" {
				labels = strings.Split(match[3], ",")
			}

			registered = append(registered, registeredMetric{name: match[1], kind: kind, labels: labels, help: help})
		}
	}

	return registered
}

// funcMetricKind returns the type of a GaugeFunc or CounterFunc.
func funcMetricKind(t *testing.T, metric prometheus.Metric) string {
	t.Helper()

	registry := prometheus.NewPedanticRegistry()
	require.NoError(t, registry.Register(metric.(prometheus.Collector)))

	families, err := registry.Gather()
	require.NoError(t, err)
	require.Len(t, families, 1)

	return strings.ToLower(families[0].GetType().String())
}

// metricsTable renders metrics as a Markdown table.
func metricsTable(t *testing.T, metrics []registeredMetric) string {
	t.Helper()

	var table strings.Builder

	table.WriteString("| Metric | Type | Labels | Meaning |\n|---|---|---|---|\n")

	for _, metric := range metrics {
		require.NotContains(t, metric.help, "|", "help of %s", metric.name)
		require.NotContains(t, metric.help, "\n", "help of %s", metric.name)

		labels := make([]string, 0, len(metric.labels))
		for _, label := range metric.labels {
			labels = append(labels, "`"+label+"`")
		}

		fmt.Fprintf(&table, "| `%s` | %s | %s | %s |\n", metric.name, metric.kind, strings.Join(labels, ", "), metric.help)
	}

	return table.String()
}

// renderMetricsReference renders docs/admin/metrics-reference.md.
func renderMetricsReference(t *testing.T, perReplica, serviceWide []registeredMetric) string {
	t.Helper()

	return "# Metrics reference\n\n" +
		"For: admins. You scrape the server's metrics with Prometheus.\n\n" +
		"<!-- Generated by `make generate-docs` from the metrics' Help text. Do not edit this file; change the Help text in the code instead. -->\n\n" +
		"This page lists every metric of the server. [configuration.md](configuration.md#endpoints) explains the two metrics ports and what to scrape.\n\n" +
		"## Per-replica metrics\n\n" +
		"Each replica serves these on its metrics port (`VAULT_SYNC_METRICS_LISTEN_ADDRESS`, `/metrics`), besides the standard Go runtime (`go_*`) and process (`process_*`) metrics.\n\n" +
		metricsTable(t, perReplica) + "\n" +
		"## Service-wide metrics\n\n" +
		"These describe the whole deployment. Every replica serves the same values, only on its service-wide metrics port (`VAULT_SYNC_SERVICE_METRICS_LISTEN_ADDRESS`, `/metrics`). [configuration.md](../configuration.md#service-wide-metrics) explains how they are refreshed.\n\n" +
		metricsTable(t, serviceWide)
}

// TestMetricsReferenceIsCurrent fails when docs/admin/metrics-reference.md
// differs from the registered metrics. Run `make generate-docs` to rewrite
// it.
func TestMetricsReferenceIsCurrent(t *testing.T) {
	perReplica := perReplicaMetrics(t)
	serviceWide := collectorMetrics(t, servicemetrics.NewMetrics().Collectors())

	for _, metric := range serviceWide {
		assert.True(t, strings.HasPrefix(metric.name, "vault_sync_service_"), "service-wide metric %s must be named vault_sync_service_*", metric.name)
	}

	for _, metric := range perReplica {
		assert.False(t, strings.HasPrefix(metric.name, "vault_sync_service_"), "per-instance metric %s must not be named vault_sync_service_*", metric.name)
	}

	rendered := renderMetricsReference(t, perReplica, serviceWide)

	if *updateMetricsReference {
		require.NoError(t, os.WriteFile(metricsReferencePath, []byte(rendered), 0o600))
	}

	current, err := os.ReadFile(metricsReferencePath)
	require.NoError(t, err)
	assert.Equal(t, rendered, string(current), "%s is stale: run 'make generate-docs' and commit the result", metricsReferencePath)
}
