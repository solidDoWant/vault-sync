// Command gen generates the tables used by path_key derivation in Go
// (internal/pathkey) and TypeScript (plugin/src/core/pathkey): full case
// folding from the vendored Unicode CaseFolding.txt, and canonical
// normalization (NFD/NFC) data from the vendored UnicodeData.txt and
// CompositionExclusions.txt, so both languages fold and normalize identically
// whatever Unicode version their runtime has. Run it via
// `go generate ./internal/pathkey`.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"slices"
	"strconv"
	"strings"
)

// UnicodeVersion is the version of the vendored CaseFolding.txt.
const UnicodeVersion = "17.0.0"

// SourceFile is the vendored Unicode data file, relative to this package.
const SourceFile = "CaseFolding-" + UnicodeVersion + ".txt"

// LicenseFile is the Unicode License v3 notice covering SourceFile and the
// generated tables, relative to this package.
const LicenseFile = "LICENSE-UNICODE.txt"

// Mapping is one full case-folding mapping (status C or F).
type Mapping struct {
	From rune
	To   []rune
}

func main() {
	source := flag.String("source", SourceFile, "path to CaseFolding.txt")
	license := flag.String("license", LicenseFile, "path to the Unicode license notice embedded in the TypeScript table")
	goOut := flag.String("go-out", "", "output path for the Go table")
	tsOut := flag.String("ts-out", "", "output path for the TypeScript table")
	unicodeData := flag.String("unicode-data", UnicodeDataFile, "path to the gzipped UnicodeData.txt")
	exclusions := flag.String("exclusions", ExclusionsFile, "path to CompositionExclusions.txt")
	goNormOut := flag.String("go-norm-out", "", "output path for the Go normalization tables")
	tsNormOut := flag.String("ts-norm-out", "", "output path for the TypeScript normalization tables")

	flag.Parse()

	if err := run(*source, *license, *goOut, *tsOut); err != nil {
		log.Fatal(err)
	}

	if err := runNormalization(*unicodeData, *exclusions, *goNormOut, *tsNormOut); err != nil {
		log.Fatal(err)
	}
}

func runNormalization(unicodeData, exclusions, goOut, tsOut string) error {
	normalization, err := LoadNormalization(unicodeData, exclusions)
	if err != nil {
		return err
	}

	goTables, err := RenderGoNormalization(normalization)
	if err != nil {
		return err
	}

	if err := os.WriteFile(goOut, goTables, 0o644); err != nil {
		return err
	}

	return os.WriteFile(tsOut, RenderTypeScriptNormalization(normalization), 0o644)
}

func run(source, license, goOut, tsOut string) error {
	file, err := os.Open(source)
	if err != nil {
		return err
	}
	defer file.Close() //nolint:errcheck // read-only

	mappings, err := Parse(file)
	if err != nil {
		return err
	}

	goTable, err := RenderGo(mappings)
	if err != nil {
		return err
	}

	if err := os.WriteFile(goOut, goTable, 0o644); err != nil {
		return err
	}

	notice, err := os.ReadFile(license)
	if err != nil {
		return err
	}

	return os.WriteFile(tsOut, RenderTypeScript(mappings, notice), 0o644)
}

// Parse reads CaseFolding.txt and returns the full, locale-independent
// mappings (statuses C and F; S and T are skipped), sorted by code point.
func Parse(reader io.Reader) ([]Mapping, error) {
	var mappings []Mapping

	scanner := bufio.NewScanner(reader)
	for line := 1; scanner.Scan(); line++ {
		text, _, _ := strings.Cut(scanner.Text(), "#")
		if strings.TrimSpace(text) == "" {
			continue
		}

		fields := strings.Split(text, ";")
		if len(fields) < 3 {
			return nil, fmt.Errorf("line %d: expected at least 3 fields", line)
		}

		status := strings.TrimSpace(fields[1])
		if status != "C" && status != "F" {
			continue
		}

		from, err := parseCodePoint(fields[0])
		if err != nil {
			return nil, fmt.Errorf("line %d: %w", line, err)
		}

		var to []rune

		for _, field := range strings.Fields(fields[2]) {
			codePoint, err := parseCodePoint(field)
			if err != nil {
				return nil, fmt.Errorf("line %d: %w", line, err)
			}

			to = append(to, codePoint)
		}

		if len(to) == 0 {
			return nil, fmt.Errorf("line %d: empty mapping", line)
		}

		mappings = append(mappings, Mapping{From: from, To: to})
	}

	if err := scanner.Err(); err != nil {
		return nil, err
	}

	slices.SortFunc(mappings, func(left, right Mapping) int { return int(left.From - right.From) })

	for index := 1; index < len(mappings); index++ {
		if mappings[index].From == mappings[index-1].From {
			return nil, fmt.Errorf("duplicate mapping for %U", mappings[index].From)
		}
	}

	return mappings, nil
}

func parseCodePoint(field string) (rune, error) {
	value, err := strconv.ParseUint(strings.TrimSpace(field), 16, 32)
	if err != nil {
		return 0, fmt.Errorf("invalid code point %q: %w", field, err)
	}

	if value > 0x10FFFF || (value >= 0xD800 && value <= 0xDFFF) {
		return 0, fmt.Errorf("code point %X is not a Unicode scalar value", value)
	}

	return rune(value), nil
}

const header = "Code generated by internal/pathkey/gen from " + SourceFile + ". DO NOT EDIT."

// RenderGo renders the Go table for package pathkey.
func RenderGo(mappings []Mapping) ([]byte, error) {
	var buffer bytes.Buffer

	fmt.Fprintf(&buffer, "// %s\n\n", header)
	fmt.Fprintf(&buffer, "// Derived from Unicode data under the Unicode License v3; see\n// internal/pathkey/gen/%s.\n\npackage pathkey\n\n", LicenseFile)
	fmt.Fprintf(&buffer, "// unicodeVersion is the Unicode version of the case-folding table.\nconst unicodeVersion = %q\n\n", UnicodeVersion)
	buffer.WriteString("// foldTable maps each code point to its full case folding (CaseFolding.txt\n// statuses C and F). Code points not listed fold to themselves.\n")
	buffer.WriteString("var foldTable = map[rune]string{\n")

	for _, mapping := range mappings {
		fmt.Fprintf(&buffer, "\t0x%04X: %s,\n", mapping.From, strconv.QuoteToASCII(string(mapping.To)))
	}

	buffer.WriteString("}\n")

	return format.Source(buffer.Bytes())
}

// RenderTypeScript renders the TypeScript table for plugin/src/core/pathkey.
// Entries are comma-separated; each is the source code point followed by the
// folded code points, all in hex and space-separated. The Unicode licence
// notice is embedded as a legal comment ("/*!"), which esbuild keeps in the
// plugin bundle, so the notice travels with every copy of the table.
func RenderTypeScript(mappings []Mapping, notice []byte) []byte {
	var buffer bytes.Buffer

	fmt.Fprintf(&buffer, "// %s\n\n", header)
	fmt.Fprintf(&buffer, "/*!\n * Derived from Unicode data under the Unicode License v3\n * (internal/pathkey/gen/%s in the vault-sync repository):\n *\n", LicenseFile)

	for _, line := range strings.Split(strings.TrimRight(string(notice), "\n"), "\n") {
		buffer.WriteString(strings.TrimRight(" * "+strings.ReplaceAll(line, "*/", "* /"), " ") + "\n")
	}

	buffer.WriteString(" */\n\n")
	fmt.Fprintf(&buffer, "/** Unicode version of the case-folding table. */\nexport const UNICODE_VERSION = %q;\n\n", UnicodeVersion)
	buffer.WriteString("/**\n * Full case folding (CaseFolding.txt statuses C and F) as comma-separated\n * entries of space-separated hex code points: source, then its folding.\n */\n")
	buffer.WriteString("export const CASE_FOLDING_DATA =\n")

	const perLine = 8

	for start := 0; start < len(mappings); start += perLine {
		end := min(start+perLine, len(mappings))
		entries := make([]string, 0, end-start)

		for _, mapping := range mappings[start:end] {
			parts := []string{strconv.FormatInt(int64(mapping.From), 16)}
			for _, codePoint := range mapping.To {
				parts = append(parts, strconv.FormatInt(int64(codePoint), 16))
			}

			entries = append(entries, strings.Join(parts, " "))
		}

		separator := ","
		terminator := " +\n"

		if end == len(mappings) {
			separator = ""
			terminator = ";\n"
		}

		fmt.Fprintf(&buffer, "  %q%s", strings.Join(entries, ",")+separator, terminator)
	}

	return buffer.Bytes()
}
