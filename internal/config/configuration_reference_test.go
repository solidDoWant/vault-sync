package config_test

import (
	"flag"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"strconv"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// The configuration reference page is generated from the doc comments of
// the *Env constants in config.go. Each const block that declares them is
// one section of the page, titled by the block's doc comment; each
// constant's doc comment is a description followed by a paragraph that
// starts "Default: ".

var updateConfigurationReference = flag.Bool("update", false, "rewrite "+configurationReferencePath)

const (
	configurationReferencePath = "../../docs/admin/configuration-reference.md"
	defaultPrefix              = "Default: "
)

type documentedVariable struct {
	name        string
	defaultText string
	description string
}

type variableSection struct {
	title     string
	variables []documentedVariable
}

// commentParagraphs returns the paragraphs of a comment group, each with its
// lines joined by spaces.
func commentParagraphs(group *ast.CommentGroup) []string {
	if group == nil {
		return nil
	}

	paragraphs := []string{}
	current := []string{}

	for _, line := range group.List {
		text := strings.TrimSpace(strings.TrimPrefix(line.Text, "//"))
		if text == "" {
			if len(current) > 0 {
				paragraphs = append(paragraphs, strings.Join(current, " "))
				current = []string{}
			}

			continue
		}

		current = append(current, text)
	}

	if len(current) > 0 {
		paragraphs = append(paragraphs, strings.Join(current, " "))
	}

	return paragraphs
}

// documentedSections parses config.go and returns its environment variables,
// one section per const block, in source order.
func documentedSections(t *testing.T) []variableSection {
	t.Helper()

	file, err := parser.ParseFile(token.NewFileSet(), "config.go", nil, parser.ParseComments)
	require.NoError(t, err)

	sections := []variableSection{}

	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}

		section := variableSection{}

		for _, spec := range general.Specs {
			value := spec.(*ast.ValueSpec)
			if len(value.Names) != 1 || !strings.HasSuffix(value.Names[0].Name, "Env") {
				continue
			}

			constant := value.Names[0].Name
			require.Len(t, value.Values, 1, constant)

			literal, ok := value.Values[0].(*ast.BasicLit)
			require.True(t, ok, "%s must be a string literal", constant)

			name, err := strconv.Unquote(literal.Value)
			require.NoError(t, err, constant)

			paragraphs := commentParagraphs(value.Doc)
			require.GreaterOrEqual(t, len(paragraphs), 2, "%s needs a doc comment: a description, then a %q paragraph", constant, defaultPrefix)
			last := paragraphs[len(paragraphs)-1]
			require.True(t, strings.HasPrefix(last, defaultPrefix), "the doc comment of %s must end with a %q paragraph", constant, defaultPrefix)

			description := strings.Join(paragraphs[:len(paragraphs)-1], " ")
			require.NotContains(t, description, "|", "%s: a table cell cannot hold a |", constant)

			section.variables = append(section.variables, documentedVariable{
				name:        name,
				defaultText: strings.TrimPrefix(last, defaultPrefix),
				description: description,
			})
		}

		if len(section.variables) == 0 {
			continue
		}

		titles := commentParagraphs(general.Doc)
		require.Len(t, titles, 1, "the const block of %s needs a one-line doc comment naming its section", section.variables[0].name)
		section.title = strings.TrimSuffix(titles[0], ".")
		sections = append(sections, section)
	}

	return sections
}

func renderConfigurationReference(sections []variableSection) string {
	var page strings.Builder

	page.WriteString("# Configuration reference\n\n" +
		"For: admins. You set the server's environment variables, directly or through the Helm chart.\n\n" +
		"<!-- Generated by `make generate-docs` from the doc comments of the environment-variable constants in internal/config/config.go. Do not edit this file; change those comments instead. -->\n\n" +
		"This page lists every environment variable of `vault-sync-server`. [configuration.md](configuration.md) explains how the server reads them and which variables each subcommand reads.\n")

	for _, section := range sections {
		page.WriteString("\n## " + section.title + "\n\n" +
			"| Variable | Default | Description |\n" +
			"|---|---|---|\n")

		for _, variable := range section.variables {
			page.WriteString("| `" + variable.name + "` | " + variable.defaultText + " | " + variable.description + " |\n")
		}
	}

	return page.String()
}

func TestConfigurationReferenceIsCurrent(t *testing.T) {
	sections := documentedSections(t)
	require.NotEmpty(t, sections)

	seen := map[string]bool{}

	for _, section := range sections {
		for _, variable := range section.variables {
			assert.True(t, strings.HasPrefix(variable.name, "VAULT_SYNC_"), variable.name)
			assert.False(t, seen[variable.name], "%s is declared twice", variable.name)
			seen[variable.name] = true
		}
	}

	page := renderConfigurationReference(sections)

	if *updateConfigurationReference {
		require.NoError(t, os.WriteFile(configurationReferencePath, []byte(page), 0o644))
	}

	current, err := os.ReadFile(configurationReferencePath)
	require.NoError(t, err)
	assert.Equal(t, page, string(current), "%s is stale: run make generate-docs", configurationReferencePath)
}
